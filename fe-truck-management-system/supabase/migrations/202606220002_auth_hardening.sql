-- ATMS authentication hardening and explicit API grants.
-- Run after 202606220001_archive_mvp.sql.

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, email, role, status)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)),
    new.email,
    'observer',
    'active'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

-- PostgreSQL privileges expose the API surface. RLS remains the final
-- authorization layer for every authenticated operation.
grant usage on schema public to authenticated;
grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on all functions in schema public to authenticated;

alter default privileges in schema public
grant select, insert, update, delete on tables to authenticated;

alter default privileges in schema public
grant usage, select on sequences to authenticated;

alter default privileges in schema public
grant execute on functions to authenticated;

notify pgrst, 'reload schema';

