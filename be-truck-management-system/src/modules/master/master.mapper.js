export function getResourceConfig(resource) {
  const config = resourceConfig[resource];
  if (!config) {
    const error = new Error(`Resource ${resource} tidak dikenal.`);
    error.statusCode = 404;
    error.code = 'RESOURCE_NOT_FOUND';
    throw error;
  }
  return config;
}
